#!/usr/bin/env node
/**
 * Generates TypeScript types from src/locales/en/*.json for type-safe t() keys.
 * Run: node scripts/generate-i18n-types.js
 * Output: src/types/generated-i18n-keys.ts
 */

const fs = require('fs');
const path = require('path');

const LOCALES_EN = path.join(__dirname, '../src/locales/en');
const OUT_FILE = path.join(__dirname, '../src/types/generated-i18n-keys.ts');
const NAMESPACES = ['common', 'screens', 'game', 'errors', 'categories', 'components'];

function flattenKeys(obj, prefix = '') {
  const keys = [];
  for (const key of Object.keys(obj)) {
    const fullKey = prefix ? `${prefix}.${key}` : key;
    const value = obj[key];
    if (value !== null && typeof value === 'object' && !Array.isArray(value)) {
      keys.push(...flattenKeys(value, fullKey));
    } else {
      keys.push(fullKey);
    }
  }
  return keys;
}

function toUnionType(keys) {
  if (keys.length === 0) return 'never';
  const quoted = keys.map((k) => `'${k.replace(/'/g, "\\'")}'`).sort();
  return quoted.join(' | ');
}

function main() {
  const namespaces = {};
  for (const ns of NAMESPACES) {
    const filePath = path.join(LOCALES_EN, `${ns}.json`);
    if (!fs.existsSync(filePath)) {
      console.warn(`Warning: ${filePath} not found, skipping.`);
      continue;
    }
    const content = fs.readFileSync(filePath, 'utf8');
    let data;
    try {
      data = JSON.parse(content);
    } catch (e) {
      console.error(`Error parsing ${filePath}:`, e.message);
      process.exit(1);
    }
    namespaces[ns] = flattenKeys(data);
  }

  const lines = [
    '// AUTO-GENERATED by scripts/generate-i18n-types.js — do not edit by hand.',
    '// Re-run: npm run i18n:generate-types',
    '',
    '/** Flattened translation keys per namespace (from en/*.json). Use for type-safe t() calls. */',
    '',
  ];

  for (const [ns, keys] of Object.entries(namespaces)) {
    const name = ns.charAt(0).toUpperCase() + ns.slice(1) + 'Key';
    lines.push(`export type ${name} = ${toUnionType(keys)};`);
    lines.push('');
  }

  lines.push('/** All valid keys for the default namespace (common). */');
  lines.push(`export type DefaultNSKey = CommonKey;`);
  lines.push('');
  lines.push('/** All valid keys with optional namespace prefix (e.g. "screens:home.title"). */');
  const fullKeyParts = NAMESPACES.filter((n) => namespaces[n]?.length).map(
    (ns) => (ns === 'common' ? 'CommonKey' : `\`${ns}:\${${ns.charAt(0).toUpperCase() + ns.slice(1)}Key}\``)
  );
  lines.push(`export type TranslationKey = ${fullKeyParts.join(' | ')};`);
  lines.push('');

  fs.writeFileSync(OUT_FILE, lines.join('\n'), 'utf8');
  console.log('Wrote', OUT_FILE);
}

main();
